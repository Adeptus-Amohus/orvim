export function translateAdditionalLabel(value, translate) {
  if (value.endsWith(":")) {
    const label = translate(value.slice(0, -1));
    if (label) return label + ":";
  }
  for (const prefix of ["Error: ", "Ошибка: "]) {
    if (value.startsWith(prefix)) {
      const translated = translate(value.slice(prefix.length));
      if (translated) return "Error: " + translated;
    }
  }
  if (value.startsWith("Страховка от случайного удаления")) {
    const count = value.match(/Хранятся последние (\d+)/)?.[1] || "24";
    return (
      `Protection against accidental deletion: after changes, a snapshot is saved at most once an hour. The latest ${count} snapshots are kept; older ones are replaced. No snapshot is created if nothing changed. ` +
      (value.includes("зашифрованы")
        ? "These are saved states, not hours of coverage. An additional snapshot may be created on restart or before important changes. Backups are encrypted with this device's key. Create a password-protected backup for another device or a reinstall."
        : (value.match(/Папка: (.*?)\. (?:Последняя|Копий)/)?.[1]
            ? "Folder: " +
              value.match(/Папка: (.*?)\. (?:Последняя|Копий)/)[1] +
              ". "
            : "") +
          (value.includes("Копий пока нет.")
            ? "No backups yet. "
            : "Latest backup: " +
              (value.match(
                /Последняя копия: (.*?)(?= Внешняя папка:| Пока только| Сохраняются|$)/,
              )?.[1] || "—") +
              " ") +
          (value.match(/Внешняя папка: (.*)\.$/)?.[1]
            ? "External folder: " +
              value.match(/Внешняя папка: (.*)\.$/)[1] +
              ". "
            : "") +
          (value.includes("удаление приложения удалит")
            ? "Stored inside the app only: uninstalling will delete these backups."
            : "Backups are stored outside the app."))
    );
  }
  const months = {
    янв: "Jan",
    февр: "Feb",
    мар: "Mar",
    март: "Mar",
    апр: "Apr",
    мая: "May",
    июн: "Jun",
    июл: "Jul",
    авг: "Aug",
    сент: "Sep",
    окт: "Oct",
    нояб: "Nov",
    дек: "Dec",
  };
  const date = value.match(
    /^(\d{1,2}) (янв|февр|мар|март|апр|мая|июн|июл|авг|сент|окт|нояб|дек)\.(.*)$/,
  );
  if (date)
    return months[date[2]] + " " + date[1] + (translate(date[3]) || date[3]);
  const rules = [
    [
      /^Доступно: ([а-я, ]+)\.$/,
      (_, types) =>
        "Available: " +
        types
          .split(", ")
          .map(
            (type) =>
              ({ шаги: "steps", сон: "sleep", тренировки: "workouts" })[type] ||
              type,
          )
          .join(", ") +
        ".",
    ],
    [
      /^Коллекция «(.+)» и её записи будут удалены: (\d+)\. Удаление можно отменить\.$/,
      "Collection “$1” and its $2 records will be deleted. You can undo deletion.",
    ],
    [
      /^Отмечено дней: (.+)\. К прошлому месяцу: (.+) балла из 5\. По записанным дням\.$/,
      "Days logged: $1. Compared with last month: $2 points out of 5. Based on logged days.",
    ],
    [/^Копий: (\d+) · последняя (.+)$/, "Backups: $1 · latest $2"],
    [/^Проверено: (.+)$/, "Checked: $1"],
    [/^Идентификатор ПК: (.+)$/, "PC ID: $1"],
    [/^Б (.+) · Ж (.+) · У (.+) г$/, "P $1 · F $2 · C $3 g"],
    [
      /^Б ([\d.,]+)\s*\/\s*Ж ([\d.,]+)\s*\/\s*У ([\d.,]+) г$/,
      "P $1 / F $2 / C $3 g",
    ],
    [/^(.+): ([\d, .]+) шагов$/, "$1: $2 steps"],
    [/^Дней с данными: (.+)$/, "Days with data: $1"],
    [/^(\d+) тренировок$/, "$1 workouts"],
    [
      /^Начало дня в (.+) · питание, сон, шаги и тренировки$/,
      "Day starts at $1 · nutrition, sleep, steps and workouts",
    ],
    [/^Вес · (.+) кг · график и записи$/, "Weight · $1 kg · chart and entries"],
    [/^Установлена версия (.+)$/, "Installed version $1"],
    [/^(\d+) из (\d+) задач$/, "$1 of $2 tasks"],
    [/^(\d+) записей$/, "$1 entries"],
    [/^(\d+) месяца?$/, "$1 months"],
    [/^(\d+) ч$/, "$1 h"],
    [/^До вашей цели ещё (.+) мл$/, "$1 ml remaining to your goal"],
    [/^Добавить (.+) мл воды$/, "Add $1 ml of water"],
    [
      /^Вода (.+) из (.+) мл\. Добавить (.+) мл$/,
      "Water $1 of $2 ml. Add $3 ml",
    ],
    [/^Настроение: (\d+) из 5$/, "Mood: $1 out of 5"],
    [/^Энергия: (\d+) из 5$/, "Energy: $1 out of 5"],
    [/^Стресс: (\d+) из 5$/, "Stress: $1 out of 5"],
  ];
  for (const [pattern, replacement] of rules)
    if (pattern.test(value)) return value.replace(pattern, replacement);
  // Translate only the UI prefix; never translate the user's title after it.
  for (const [ru, en] of [
    ["Действия с записью: ", "Entry actions: "],
    ["Действия с задачей: ", "Task actions: "],
    ["Завершить задачу: ", "Complete task: "],
    ["Изменить задачу: ", "Edit task: "],
    ["Назначить дату и время: ", "Schedule date and time: "],
    ["Перенести задачу: ", "Move task: "],
    ["Перетащить в расписание: ", "Drag into schedule: "],
    ["Изменить событие: ", "Edit event: "],
    ["Изменить длительность: ", "Change duration: "],
    ["Перенести время: ", "Move time: "],
    ["Этап задачи: ", "Task stage: "],
    ["Запланировано: ", "Scheduled: "],
    ["Удалить мысль: ", "Delete thought: "],
    ["Не сохранено: ", "Not saved: "],
    ["Сохранить в: ", "Save to: "],
    ["Распознано: ", "Recognized: "],
    ["Открыть: ", "Open: "],
    ["Оценить: ", "Rate: "],
    ["Убрать файл: ", "Remove file: "],
  ])
    if (value.startsWith(ru)) return en + value.slice(ru.length);
  // Dynamic control captions combine a label with a value or formatted date.
  for (const separator of [": ", " · "]) {
    if (!value.includes(separator)) continue;
    const parts = value.split(separator),
      translated = parts.map((part) => translate(part) || part);
    if (translated.some((part, i) => part !== parts[i]))
      return translated.join(separator);
  }
  if (/\d/.test(value)) {
    const next = value.replace(/\b(\d+(?:[.,]\d+)?)\s*мл\b/gu, "$1 ml");
    // Cyrillic units have no ASCII word boundary on the right.
    const units = next
      .replace(/(\d(?:[\d\s.,]*\d)?)\s*ккал(?=\s|$|[.,/·])/gu, "$1 kcal")
      .replace(/(\d(?:[\d\s.,]*\d)?)\s*кг(?=\s|$|[.,/·])/gu, "$1 kg")
      .replace(/(\d(?:[\d\s.,]*\d)?)\s*г(?=\s|$|[.,/·])/gu, "$1 g")
      .replace(/(\d(?:[\d\s.,]*\d)?)\s*ч(?=\s|$|[.,/·])/gu, "$1 h")
      .replace(/(\d(?:[\d\s.,]*\d)?)\s*км(?=\s|$|[.,/·])/gu, "$1 km")
      .replace(/(\d(?:[\d\s.,]*\d)?)\s*раз(?=\s|$|[.,/·])/gu, "$1 reps")
      .replace(
        /(\d(?:[\d\s.,]*\d)?)\s*подход(?:а|ов)?(?=\s|$|[.,/·])/gu,
        "$1 sets",
      )
      .replace(
        /(\d(?:[\d\s.,]*\d)?)\s*шаг(?:а|ов)?(?=\s|$|[.,/·])/gu,
        "$1 steps",
      )
      .replace(/(\d(?:[\d\s.,]*\d)?)\s*с(?=\s|$|[.,/·])/gu, "$1 s")
      .replace(/(\d(?:[\d\s.,]*\d)?)\s*КБ(?=\s|$|[.,/·])/gu, "$1 KB")
      .replace(/(\d(?:[\d\s.,]*\d)?)\s*МБ(?=\s|$|[.,/·])/gu, "$1 MB")
      .replace(/(\d+(?:[.,]\d+)?)\s*мл(?=\s|$|[.,/])/gu, "$1 ml")
      .replace(/(\d+)\s*мин(?=\s|$|[.,/])/gu, "$1 min");
    if (units !== value) return units;
  }
  return null;
}

